export function t(lang: Lang, key: string): string {
  return UI[lang][key] ?? UI.en[key] ?? key
}

/** Normalize text for cross-language search (diacritics, Arabic letter variants). */
export function normalize(s: string): string {
  return s
    .toLowerCase()
    .replace(/[\u064B-\u0652\u0640]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[«»“”'’.,!?;:()\-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}
